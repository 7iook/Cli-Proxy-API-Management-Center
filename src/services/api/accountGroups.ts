/**
 * Account groups (display-only registry). The backend owns group definitions,
 * including empty groups and their order. Never used for scheduling.
 */

import { apiClient } from './client';
import { isRecord } from '@/utils/helpers';

export interface AccountGroup {
  id: string;
  name: string;
  color?: string;
}

export interface AccountGroupSaveResult {
  groups: AccountGroup[];
  cleared: number;
}

export interface AccountGroupAssignResult {
  updated: string[];
  failed: Array<{ name: string; error: string }>;
}

const PATH = '/account-groups';

export const normalizeAccountGroups = (value: unknown): AccountGroup[] => {
  if (!Array.isArray(value)) return [];
  return value.flatMap((item) => {
    if (!isRecord(item)) return [];
    const id = typeof item.id === 'string' ? item.id.trim() : '';
    const name = typeof item.name === 'string' ? item.name.trim() : '';
    if (!id || !name) return [];
    const color = typeof item.color === 'string' ? item.color.trim() : '';
    return [color ? { id, name, color } : { id, name }];
  });
};

const normalizeAssignResult = (payload: unknown): AccountGroupAssignResult => {
  const record = isRecord(payload) ? payload : {};
  const updated = Array.isArray(record.updated)
    ? record.updated.filter((name): name is string => typeof name === 'string')
    : [];
  const failed = Array.isArray(record.failed)
    ? record.failed.flatMap((item) =>
        isRecord(item) && typeof item.name === 'string'
          ? [{ name: item.name, error: typeof item.error === 'string' ? item.error : '' }]
          : []
      )
    : [];
  return { updated, failed };
};

export const accountGroupsApi = {
  async list(): Promise<AccountGroup[]> {
    const data = await apiClient.get<unknown>(PATH);
    return normalizeAccountGroups(isRecord(data) ? data.groups : undefined);
  },

  /** Replaces the whole ordered list; empty ids are generated by the server. */
  async replace(groups: Array<Pick<AccountGroup, 'name' | 'color'> & { id?: string }>) {
    const data = await apiClient.put<unknown>(PATH, { groups });
    const record = isRecord(data) ? data : {};
    return {
      groups: normalizeAccountGroups(record.groups),
      cleared: typeof record.cleared === 'number' ? record.cleared : 0,
    } satisfies AccountGroupSaveResult;
  },

  /** groupId '' removes the accounts from their group. */
  async assign(groupId: string, names: string[]): Promise<AccountGroupAssignResult> {
    const data = await apiClient.post<unknown>(`${PATH}/assign`, {
      group_id: groupId,
      names,
    });
    return normalizeAssignResult(data);
  },
};
